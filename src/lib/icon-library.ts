export const ICON_GROUPS: string[] = ["Todos", "Finanzas", "Comercio", "Comida", "Hogar", "Transporte", "Tecnología", "Salud", "Educación", "Entretenimiento", "Servicios", "Herramientas", "Naturaleza", "Personas", "Símbolos"];

/** name de lucide -> componente (para resolver iconos guardados por nombre). */
export const NAME_ICON_MAP: Record<string, LucideIcon> = Object.fromEntries(
  ICON_LIBRARY.map((e) => [e.name, e.Component]),
);

/** Busca en la biblioteca por nombre, etiqueta o keywords (insensible a mayusculas/acentos). */
export function searchIcons(query: string, grupo = "Todos"): IconLibraryEntry[] {
  const norm = (s: string) =>
    s.toLowerCase().normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  const q = norm(query.trim());
  return ICON_LIBRARY.filter((e) => {
    if (grupo !== "Todos" && e.grupo !== grupo) return false;
    if (!q) return true;
    return (
      norm(e.name).includes(q) ||
      norm(e.label).includes(q) ||
      norm(e.keywords).includes(q)
    );
  });
}
